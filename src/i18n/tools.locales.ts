/** Merge a locale strip over the EN base — key-safe, string-only. */
export function toolStrings<B extends Record<string, string>>(base: B, locale: Locale, key: ToolKey): B {
  const strip = { ...STRIPS[locale]?.[key as ToolKey], ...LEGACY_STRIPS[locale]?.[key as Exclude<ToolKey, 'cusp'>] };
  if (!strip) return base;
  const out = { ...base } as Record<string, string>;
  for (const [k, v] of Object.entries(strip)) {
    if (typeof v === 'string' && k in base) out[k] = v;
  }
  return out as B;
}
